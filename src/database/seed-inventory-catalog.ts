const SIDES = {
  m: ['левый', 'правый'],
  f: ['левая', 'правая'],
  n: ['левое', 'правое'],
} as const;

function vehicleRow(type: PartType, car: Car): Spec {
  const [make, model, from, to, origin, k] = car;
  const years = `${from}–${to ?? ''}`;
  const sideIdx = type.side ? Math.floor(rand() * 2) : -1;
  const ruSide = type.side ? ` ${SIDES[type.side][sideIdx]}` : '';
  const hySide = type.side ? `, ${['ձախ', 'աջ'][sideIdx]}` : '';
  const enSide = type.side ? `, ${['left', 'right'][sideIdx]}` : '';
  const brand = type.used ? make : pick(BRANDS[type.kind][origin]);
  const fits: Fit[] = [[make, model, from, to]];
  return finish({
    cat: type.cat,
    brand,
    pn: null,
    ru: `${type.ru}${ruSide} ${make} ${model} ${years}${type.used ? ', оригинал б/у' : ''}`,
    hy: `${type.hy}${hySide} ${make} ${model} ${years}${type.used ? ', օրիգինալ, օգտագործված' : ''}`,
    en: `${type.en}${enSide} ${make} ${model} ${years}${type.used ? ', genuine, used' : ''}`,
    fits,
    price: type.price * k,
    stock: type.used ? 1 : undefined,
    sold: type.used ? 0 : undefined,
    supplier: type.used ? 3 : type.kind === 'accessory' ? 1 : pick([0, 1]),
    used: type.used,
    shelf:
      type.used || type.kind === 'body'
        ? `Склад-${1 + Math.floor(rand() * 3)}`
        : undefined,
  });
}

