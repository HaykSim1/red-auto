export function generateCatalog(count: number): Spec[] {
  const lines = [
    ...take(filters(), 110),
    ...take(oils(), 110),
    ...take(tires(), 80),
    ...take(bulbs(), 45),
    ...take(belts(), 30),
    ...take(plugs(), 50),
    ...take(wipers(), 30),
    ...take(batteries(), 40),
    ...fixed(),
  ];
  const seen = new Set<string>();
  const out: Spec[] = [];
  const add = (spec: Spec): boolean => {
    const key = `${spec.brand}|${spec.ru}|${spec.pn ?? ''}`;
    if (seen.has(key)) return false;
    seen.add(key);
    out.push(spec);
    return true;
  };
  for (const spec of lines) {
    if (out.length < count) add(spec);
  }
  // Fill the rest round-robin over part types so every category gets stock.
  const queues = TYPES.map((type) =>
    shuffled(CARS.filter((c) => !type.only || c[4] === type.only)),
  );
  for (let round = 0; out.length < count; round++) {
    let progressed = false;
    for (let i = 0; i < TYPES.length && out.length < count; i++) {
      const car = queues[i][round];
      if (!car) continue;
      progressed = true;
      add(vehicleRow(TYPES[i], car));
    }
    if (!progressed) break;
  }
  return shuffled(out);
}
