/**
 * Bulk demo catalogue for seed-inventory.ts. Two kinds of rows:
 *  - product lines with their real designations (oils, tires, bulbs, filters,
 *    spark plugs, belts, wipers, batteries, LPG equipment, electronics);
 *  - vehicle-specific parts by real aftermarket brands, WITHOUT a part number
 *    (brand × part type × car model is a plausible stock line, not a
 *    catalogue lookup).
 * Deterministic: the same `count` always yields the same rows.
 */
import type { Fit, Spec } from './seed-inventory';

function rng(seed: number): () => number {
  let a = seed;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = rng(1000);
const pick = <T>(list: readonly T[]): T =>
  list[Math.floor(rand() * list.length)];
function shuffled<T>(list: readonly T[]): T[] {
  const a = [...list];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
const take = <T>(list: readonly T[], n: number): T[] =>
  shuffled(list).slice(0, n);

function roundPrice(v: number): number {
  const step = v >= 20000 ? 500 : 100;
  return Math.max(step, Math.round(v / step) * step);
}
function stockFor(price: number): number {
  const [lo, hi] =
    price > 150000
      ? [1, 2]
      : price > 50000
        ? [1, 4]
        : price > 15000
          ? [2, 8]
          : price > 5000
            ? [4, 16]
            : [8, 40];
  return lo + Math.floor(rand() * (hi - lo + 1));
}
const SHELF_ROWS = 'ABCDEFGHJKLMNPRST';
const shelf = () =>
  `${SHELF_ROWS[Math.floor(rand() * SHELF_ROWS.length)]}${1 + Math.floor(rand() * 6)}-${String(1 + Math.floor(rand() * 24)).padStart(2, '0')}`;

type Row = Omit<Spec, 'cost' | 'stock' | 'price'> & {
  price: number;
  stock?: number;
};
/** Fills price rounding, cost (70–82 % of price), stock and shelf. */
function finish(row: Row): Spec {
  const price = roundPrice(row.price * (0.9 + rand() * 0.25));
  return {
    shelf: shelf(),
    ...row,
    price,
    cost: roundPrice(price * (0.7 + rand() * 0.12)),
    stock: row.stock ?? stockFor(price),
  };
}

