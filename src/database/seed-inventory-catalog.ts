function filters(): Spec[] {
  const out: Spec[] = [];
  for (const [brand, kinds] of Object.entries(FILTERS)) {
    for (const [kind, numbers] of Object.entries(kinds)) {
      const k = FILTER_KINDS[kind as keyof typeof FILTER_KINDS];
      for (const pn of numbers) {
        const carbon = /^(CUK|LAK)|A$/.test(pn) && kind === 'cabin';
        out.push(
          finish({
            cat: k.cat,
            brand,
            pn,
            ru: `${k.ru}${carbon ? ' угольный' : ''} ${pn}`,
            hy: `${k.hy}${carbon ? ' ածխային' : ''} ${pn}`,
            en: `${k.en}${carbon ? ', activated carbon' : ''} ${pn}`,
            price:
              k.price * (carbon ? 1.4 : 1) * (brand === 'Filtron' ? 0.75 : 1),
            supplier: 0,
          }),
        );
      }
    }
  }
  return out;
}

