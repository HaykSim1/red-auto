import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsEnum,
  IsIn,
  IsInt,
  IsISO8601,
  IsNumber,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  MinLength,
  ValidateNested,
} from 'class-validator';
import { InventoryMovementType } from '../../database/enums';

const MAX_QUANTITY = 1_000_000;
const MAX_MONEY = 9_999_999_999;

/** Movement types a scan can produce: `adjust` needs a deliberate number. */
export const BY_CODE_MOVEMENT_TYPES = [
  InventoryMovementType.SELL,
  InventoryMovementType.RECEIVE,
  InventoryMovementType.WRITE_OFF,
  InventoryMovementType.RETURN,
] as const;

class MovementExtrasDto {
  @ApiPropertyOptional({
    type: Number,
    nullable: true,
    minimum: 0,
    description: 'Purchase cost per unit. Only used on `receive`.',
  })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  @Max(MAX_MONEY)
  unit_cost?: number | null;

  @ApiPropertyOptional({ type: String, nullable: true })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  note?: string | null;

  @ApiPropertyOptional({
    format: 'uuid',
    description:
      'Generated by the client, one per operation. A repeat with the same id returns the original movement instead of recording a second one.',
  })
  @IsOptional()
  @IsUUID()
  client_op_id?: string;
}

export class CreateMovementDto extends MovementExtrasDto {
  @ApiProperty({ enum: InventoryMovementType })
  @IsEnum(InventoryMovementType)
  type: InventoryMovementType;

  @ApiProperty({
    minimum: 0,
    description:
      'Amount moved (>= 1) for receive / sell / write_off / return. For `adjust`: the new stock level (>= 0).',
  })
  @IsInt()
  @Min(0)
  @Max(MAX_QUANTITY)
  quantity: number;
}

export class CreateMovementByCodeDto extends MovementExtrasDto {
  @ApiProperty({ description: 'Scanned barcode, or a typed part number.' })
  @IsString()
  @MinLength(1)
  @MaxLength(120)
  code: string;

  @ApiProperty({ enum: BY_CODE_MOVEMENT_TYPES })
  @IsIn(BY_CODE_MOVEMENT_TYPES)
  type: (typeof BY_CODE_MOVEMENT_TYPES)[number];

  @ApiPropertyOptional({ default: 1, minimum: 1 })
  @IsOptional()
  @IsInt()
  @Min(1)
  @Max(MAX_QUANTITY)
  quantity?: number;
}

export class UpdateMovementDto {
  @ApiProperty({
    minimum: 0,
    description: 'Same meaning as on create, for the movement type.',
  })
  @IsInt()
  @Min(0)
  @Max(MAX_QUANTITY)
  quantity: number;
}

export class LookupItemsQueryDto {
  @ApiProperty({ description: 'Scanned barcode, or a typed part number.' })
  @IsString()
  @MinLength(1)
  @MaxLength(120)
  code: string;
}

/** Types that can be made with no connection and sent later. */
export const BATCH_MOVEMENT_TYPES = [
  InventoryMovementType.SELL,
  InventoryMovementType.RECEIVE,
] as const;

export const BATCH_MAX_OPERATIONS = 100;

export class BatchOperationDto {
  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  client_op_id: string;

  @ApiProperty({ format: 'uuid' })
  @IsUUID()
  item_id: string;

  @ApiProperty({ enum: BATCH_MOVEMENT_TYPES })
  @IsIn(BATCH_MOVEMENT_TYPES)
  type: (typeof BATCH_MOVEMENT_TYPES)[number];

  @ApiProperty({ minimum: 1 })
  @IsInt()
  @Min(1)
  @Max(MAX_QUANTITY)
  quantity: number;

  @ApiPropertyOptional({ type: Number, nullable: true, minimum: 0 })
  @IsOptional()
  @IsNumber({ maxDecimalPlaces: 2 })
  @Min(0)
  @Max(MAX_MONEY)
  unit_cost?: number | null;

  @ApiPropertyOptional({ type: String, nullable: true })
  @IsOptional()
  @IsString()
  @MaxLength(500)
  note?: string | null;

  @ApiProperty({
    description:
      'When the operation was made, by the device clock (ISO 8601). A time in the future is replaced by the server time.',
  })
  @IsISO8601()
  occurred_at: string;
}

export class BatchMovementsDto {
  @ApiProperty({ type: [BatchOperationDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(BATCH_MAX_OPERATIONS)
  @ValidateNested({ each: true })
  @Type(() => BatchOperationDto)
  operations: BatchOperationDto[];
}

export class ItemIndexQueryDto {
  @ApiPropertyOptional({
    description:
      'Only items changed at or after this time (the `server_time` of the previous sync).',
  })
  @IsOptional()
  @IsISO8601()
  updated_since?: string;

  @ApiPropertyOptional({ default: 1000, maximum: 1000 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(1000)
  limit?: number = 1000;

  @ApiPropertyOptional({
    description: 'Opaque cursor from previous page `next_cursor`.',
  })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  cursor?: string;
}
